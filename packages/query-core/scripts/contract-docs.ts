import {
  ALIASES,
  MISSING_REASONS,
  SAMPLE_COLUMNS,
  UNCARRIED,
  VIEWS,
  type Column,
} from "@countylens/contract";
import { SAMPLE_RULE } from "../src/sample.js";

const entry = (c: Column): Record<string, unknown> => ({
  name: c.name,
  type: c.type,
  kind: c.kind,
  nullable: c.nullable,
  ...(c.enum ? { enum: c.enum } : {}),
  meaning: c.meaning,
  source: c.source,
  missingReason: c.missingReason,
});

/** contract/v1/columns.json (byte-stable: the sample test compares it with this output). */
export function renderColumnsJson(): string {
  const doc = {
    contract: "contract/v1",
    generatedFrom: "packages/contract/src/columns.ts",
    views: Object.fromEntries(Object.entries(VIEWS).map(([v, cols]) => [v, cols.map(entry)])),
    sample: SAMPLE_COLUMNS.map(entry),
    // The no-carrier fields are listed in README.md, not here: a v1 column list never names them
    // (TC-010 greps this file for them).
    uncarried: "see README.md § No-carrier and not-emitted fields",
    aliases: ALIASES,
    missingReasons: MISSING_REASONS,
  };
  return `${JSON.stringify(doc, null, 2)}\n`;
}

export interface SampleSummary {
  rows: number;
  stalled: number;
  withRoofAge: number;
  nullProvenance: number;
  runId: string;
  manifestCid: string;
  asOf: string;
  tablesRoots: { data_group: string; cid: string }[];
}

const cell = (s: string): string => s.replace(/\|/g, "\\|");

function table(cols: readonly Column[]): string {
  const rows = cols.map(
    (c) =>
      `| \`${c.name}\` | \`${c.type}\` | ${c.nullable ? "yes" : "no"} | ${cell(c.meaning)}${
        c.enum ? ` (${c.enum.map((e) => `\`${e}\``).join(", ")})` : ""
      } | ${cell(c.source)} | ${c.missingReason ? `\`${c.missingReason}\`` : "never empty"} |`,
  );
  return [
    "| Column | Type | Nullable | Meaning | Source (class.property or derivation) | Missing reason |",
    "| --- | --- | --- | --- | --- | --- |",
    ...rows,
  ].join("\n");
}

function gaps(): string {
  const rows = Object.entries(UNCARRIED).flatMap(([view, fields]) =>
    fields.map(
      (u) =>
        `| \`${u.field}\` | \`${u.reason}\` | ${view} | ${cell(u.carrier)} | ${cell(u.fallback)} |`,
    ),
  );
  return [
    "| Field | Reason in `missing` | View | Why there is no carrier | Fallback |",
    "| --- | --- | --- | --- | --- |",
    ...rows,
  ].join("\n");
}

