#!/usr/bin/env bash
# Regenerates docs/progress.md: story board, gate status, status pie and a Mermaid
# git graph of the feature branch (one branch + --no-ff merge per story).
# Reads stories/*.md front matter (id, title, status, branch) and git history.
# Usage: bash scripts/progress.sh [feature-branch]
set -euo pipefail

root=$(git rev-parse --show-toplevel)
cd "$root"

feature="${1:-${FEATURE_BRANCH:-}}"
if [ -z "$feature" ]; then
  feature=$(git for-each-ref --format='%(refname:short)' 'refs/heads/feature/*' | head -n1)
fi
if [ -z "$feature" ]; then
  echo "No feature/* branch found. Pass one: bash scripts/progress.sh feature/oracle-pipeline" >&2
  exit 1
fi

out="docs/progress.md"
mkdir -p docs

# front matter field reader: fm <file> <key>
fm() {
  awk -v k="$2" '
    NR==1 && $0!="---" {exit}
    NR>1 && $0=="---" {exit}
    NR>1 {
      line=$0; sub(/[ \t]+#.*$/, "", line)
      if (index(line, k ":") == 1) { v=substr(line, length(k)+2); gsub(/^[ \t"]+|[ \t"]+$/, "", v); print v; exit }
    }' "$1"
}

# resolve a branch name to a ref that exists (local, then origin)
ref_of() {
  if git show-ref --verify --quiet "refs/heads/$1"; then echo "$1"
  elif git show-ref --verify --quiet "refs/remotes/origin/$1"; then echo "origin/$1"
  else echo ""; fi
}

gate_verdict() { # gate_verdict G4 A-03 -> newest matching docs/gates report
  local f="" g
  for g in docs/gates/"$1"-*"$2"*-precheck.md; do [ -f "$g" ] && f="$g"; done
  if [ -z "$f" ]; then echo "—"; return; fi
  case "$(fm "$f" verdict)" in
    PASS) echo "✅" ;; FAIL) echo "❌" ;; *) echo "?" ;;
  esac
}

done_n=0; prog_n=0; ready_n=0; draft_n=0; mismatch=""
rows=""; graph=""

shopt -s nullglob
stories=(stories/*.md)

for f in ${stories[@]+"${stories[@]}"}; do
  id=$(fm "$f" id); [ -z "$id" ] && continue
  title=$(fm "$f" title); status=$(fm "$f" status); branch=$(fm "$f" branch)
  [ -z "$status" ] && status="Draft"
  case "$branch" in ""|*"{"*) branch="" ;; esac

  ref=""; merged="no"; last="—"; commits=0
  if [ -n "$branch" ]; then ref=$(ref_of "$branch"); fi
  if [ -n "$ref" ]; then
    last=$(git log -1 --format=%cs "$ref")
    sha=$(git rev-parse "$ref")
    # merged = reachable from the feature branch but not on its first-parent line (i.e. arrived by a merge)
    if git merge-base --is-ancestor "$ref" "$feature" 2>/dev/null && ! git rev-list --first-parent "$feature" | grep -q "^$sha"; then
      merged="yes"
      m=$(git rev-list --first-parent --merges "$feature" | while read -r c; do
            if git merge-base --is-ancestor "$sha" "$c^2" 2>/dev/null; then echo "$c"; fi; done | tail -n1)
      [ -n "$m" ] && commits=$(git rev-list --count "$m^1..$m^2")
    else
      commits=$(git rev-list --count "$feature..$ref" 2>/dev/null || echo 0)
    fi
  fi
  if git log "$feature" --merges --format=%s 2>/dev/null | grep -q "^$id:"; then merged="yes"; fi

  case "$status" in
    Done) done_n=$((done_n+1)) ;;
    "In Progress") prog_n=$((prog_n+1)) ;;
    Ready) ready_n=$((ready_n+1)) ;;
    *) draft_n=$((draft_n+1)) ;;
  esac

  if [ "$status" = "Done" ] && [ "$merged" = "no" ]; then
    mismatch="$mismatch- **$id** is marked Done but its branch \`${branch:-unset}\` is not merged into \`$feature\`.\n"
  fi
  if [ "$status" != "Done" ] && [ "$merged" = "yes" ]; then
    mismatch="$mismatch- **$id** is merged into \`$feature\` but its status is \`$status\`; set \`status: Done\`.\n"
  fi

  evidence="—"; [ -f "docs/evidence/$id.md" ] && evidence="[✅](evidence/$id.md)"
  icon="⬜"
  case "$status" in Done) icon="✅" ;; "In Progress") icon="🔄" ;; Ready) icon="🟦" ;; esac
  rows="$rows| $icon $id | $title | $status | \`${branch:-—}\` | $merged | $(gate_verdict G4 "$id") | $(gate_verdict G5 "$id") | $(gate_verdict G6 "$id") | $(gate_verdict G7 "$id") | $evidence | $last |\n"

  gname="${branch:-$id}"
  if [ "$merged" = "yes" ] || [ "$status" = "Done" ]; then
    graph="$graph  branch \"$gname\"\n  commit id: \"$id: $commits commit(s)\"\n  checkout \"$feature\"\n  merge \"$gname\" id: \"$id done\" tag: \"$id\"\n"
  elif [ -n "$ref" ] || [ "$status" = "In Progress" ]; then
    graph="$graph  branch \"$gname\"\n  commit id: \"$id: $commits commit(s), in progress\" type: HIGHLIGHT\n  checkout \"$feature\"\n"
  fi
done

total=$((done_n+prog_n+ready_n+draft_n))
head_sha=$(git rev-parse --short "$feature" 2>/dev/null || echo "?")
now=$(date -u +"%Y-%m-%dT%H:%MZ")

{
  echo "# Delivery Progress: \`$feature\`"
  echo
  echo "Generated by \`scripts/progress.sh\` at $now from \`$feature\` @ \`$head_sha\`. Do not edit by hand."
  echo
  echo "**$done_n of $total stories done** · $prog_n in progress · $ready_n ready · $draft_n draft"
  echo
  echo "## Status"
  echo
  echo '```mermaid'
  echo "pie showData title Stories by status"
  echo "  \"Done\" : $done_n"
  echo "  \"In progress\" : $prog_n"
  echo "  \"Ready\" : $ready_n"
  echo "  \"Draft\" : $draft_n"
  echo '```'
  echo
  echo "## Branch graph (one branch and merge per story)"
  echo
  echo '```mermaid'
  echo "%%{init: { 'gitGraph': { 'mainBranchName': 'main', 'showCommitLabel': true } } }%%"
  echo "gitGraph"
  echo "  commit id: \"upstream README\""
  echo "  branch \"$feature\""
  echo "  commit id: \"bootstrap\""
  printf "%b" "$graph"
  echo '```'
  echo
  echo "## Board"
  echo
  echo "| Story | Title | Status | Branch | Merged | G4 | G5 | G6 | G7 | Evidence | Last commit |"
  echo "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"
  printf "%b" "$rows"
  echo
  echo "Legend: ✅ done · 🔄 in progress · 🟦 ready · ⬜ draft. Gate cells come from \`docs/gates/\` pre-check reports (✅ PASS, ❌ FAIL, — not run)."
  echo
  echo "## Mismatches"
  echo
  if [ -n "$mismatch" ]; then printf "%b" "$mismatch"; else echo "None: story status and git history agree."; fi
  echo
  echo "## Raw history (first parent = one line per merged story)"
  echo
  echo '```text'
  git log --first-parent --format='%h %cs %s' "$feature" | head -n 60
  echo '```'
} > "$out"

echo "Wrote $out ($done_n/$total done, feature branch $feature)"
