// Operator command `npm --prefix pipeline/oracle-runtime run render-coverage` (OR-M5).
//
// Regenerates docs/evidence/A-01-coverage.md from the catalog, so the coverage table can
// never drift from pipeline/docs/travis-sources.yaml (it said "GIS not reached" after the
// GIS count was recorded). The denominators, their source URLs and capture times come from
// the catalog; the "Published" and "Coverage" columns stay "not published yet" until A-11
// fills them from the CLI-exported Atlas tables. Deterministic: no clock, no host paths.
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { redact } from "../lib/log.js";
import { DEFAULT_REPO_ROOT } from "./blocked-evidence.js";
import type { Catalog, Measurement, SourceKey } from "./catalog.schema.js";
import { DEFAULT_CATALOG_PATH, readCatalog, writeFileAtomic } from "./write-catalog.js";

export const COVERAGE_REL_PATH = "docs/evidence/A-01-coverage.md";
const NOT_YET = "not published yet";
const NOT_APPLICABLE = "not applicable (GIS is not the population)";

interface Row {
  key: SourceKey;
  label: string;
  unit: string;
  /** Which measurement of the row is the denominator (default `denominator`). */
  pick?: "travis_coded_rows";
  published?: string;
}

const ROWS: readonly Row[] = [
  { key: "tcad_certified", label: "TCAD 2026 certified roll (properties)", unit: "accounts" },
  { key: "austin_permits", label: "Austin issued permits (`3syk-w9eu`)", unit: "rows" },
  {
    key: "tx_comptroller",
    label: "Texas Comptroller franchise-tax holders, Travis-coded (`9cir-efmm`, county 227)",
    unit: "rows",
    pick: "travis_coded_rows",
  },
  { key: "tcad_gis", label: "TCAD GIS parcels", unit: "features", published: NOT_APPLICABLE },
  { key: "other_jurisdictions", label: "Permits outside Austin", unit: "rows" },
  { key: "bbb", label: "BBB roofing contractors", unit: "listings" },
  { key: "overture", label: "Overture places", unit: "places" },
];

function groupInt(n: number): string {
  return String(n).replace(/\B(?=(\d{3})+(?!\d))/g, ",");
}

function cell(text: string): string {
  return text.replace(/\r?\n/g, " ").replace(/\|/g, "\\|").trim();
}

function utc(iso: string): string {
  return iso.replace(/\.\d+Z$/, "Z");
}

function denominatorText(m: Measurement, unit: string): string {
  if (m.value === null) return `missing: ${cell(m.missing_reason ?? "no reason recorded")}`;
  const via = m.captured_via ? ` (counted via ${cell(m.captured_via)})` : "";
  return `${groupInt(m.value)} ${unit}${via}`;
}

export function renderCoverage(catalog: Catalog): string {
  const lines = [
    "---",
    "id: EV-A-01-coverage",
    "parent: A-01",
    `created: ${catalog.snapshot_time.slice(0, 10)}`,
    "status: started (denominators from A-01; published counts are added in A-11)",
    "source_catalog: pipeline/docs/travis-sources.yaml",
    "---",
    "",
    "# Coverage: Travis County denominators vs published counts",
    "",
    "Generated by `npm --prefix pipeline/oracle-runtime run render-coverage` from `pipeline/docs/travis-sources.yaml`. Do not edit by hand. Each denominator has its source URL and UTC capture time in the catalog, and `docs/sources.md` renders them. A-11 fills the Published and Coverage columns from the CLI-exported Atlas tables; until then they read not published yet.",
    "",
    "| Source | Denominator | Denominator source | Captured (UTC) | Published | Coverage |",
    "| --- | --- | --- | --- | --- | --- |",
  ];
  for (const r of ROWS) {
    const source = catalog.sources.find((s) => s.key === r.key);
    if (!source) {
      lines.push(
        `| ${r.label} | missing: no ${r.key} row in the catalog | | | ${NOT_YET} | ${NOT_YET} |`,
      );
      continue;
    }
    const m = (r.pick ? source[r.pick] : undefined) ?? source.denominator;
    let label = r.label;
    if (r.key === "other_jurisdictions" && catalog.permits) {
      label = `${r.label} (${catalog.permits.jurisdictions.filter((j) => j.key !== "austin").length} jurisdictions)`;
    }
    const published = r.published ?? NOT_YET;
    const coverage = r.published ? "not applicable" : NOT_YET;
    lines.push(
      `| ${label} | ${denominatorText(m, r.unit)} | ${m.source_url} | ${utc(m.captured_at)} | ${published} | ${coverage} |`,
    );
  }
  return `${lines.join("\n")}\n`;
}

export interface RenderCoverageOptions {
  repoRoot?: string;
  catalogPath?: string;
  out?: (line: string) => void;
}

export function main(options: RenderCoverageOptions = {}): number {
  const out =
    options.out ??
    ((line: string) => {
      process.stdout.write(`${line}\n`);
    });
  let catalog: Catalog;
  try {
    catalog = readCatalog(options.catalogPath ?? DEFAULT_CATALOG_PATH);
  } catch (error) {
    const message = error instanceof Error ? (error.message.split("\n")[0] ?? "") : String(error);
    out(redact(`render-coverage: catalog unreadable: ${message}`));
    return 1;
  }
  writeFileAtomic(
    join(options.repoRoot ?? DEFAULT_REPO_ROOT, COVERAGE_REL_PATH),
    renderCoverage(catalog),
  );
  out(`render-coverage: wrote ${COVERAGE_REL_PATH}`);
  return 0;
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exitCode = main();
}
